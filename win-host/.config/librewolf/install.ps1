# Applies this folder to the LibreWolf profile. Rerunnable; close LibreWolf first.
#   -Update   re-download AMO extensions even if already present
#   -Install  download/refresh the portable LibreWolf build into %LOCALAPPDATA%\Programs\LibreWolf (no admin)
#   -Quick    local files only (no downloads, no addons.mozilla.org lookups); takes under a second
#   -Css      only rebuild the Sidebery config (works while LibreWolf runs; press F1 twice to reload it)
# Needs PowerShell 7 (pwsh).
param([switch]$Update, [switch]$Install, [switch]$Quick, [switch]$Css)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$appDir = "$env:LOCALAPPDATA\Programs\LibreWolf"
$exe = "$appDir\LibreWolf\librewolf.exe"
$dataDir = "$env:APPDATA\librewolf"
$sideberyId = '{3c078156-979c-498b-8990-85f7987dd929}'

# --- Sidebery managed storage (HKCU, no admin) -------------------------------------
function Write-SideberyConfig {
  # Ctrl+1..0 badges: digits for the first 10 tabs of a workspace, pins first. Unpinned tabs are
  # offset by the pin count (has pin N, lacks pin N+1). "of S" skips non-tab siblings in both lists.
  $pin = { param($i) ".tab-wrapper:nth-child($i of .tab-wrapper)" }
  $badges = foreach ($k in 1..10) { ".PinnedTabsBar $(& $pin $k) .fav::after { content: `"$($k % 10)`"; }" }
  $badges += foreach ($pins in 0..9) {
    $panel = ".TabsPanel:not(:has($(& $pin ($pins + 1))))"
    if ($pins) { $panel = ".TabsPanel:has($(& $pin $pins)):not(:has($(& $pin ($pins + 1))))" }
    foreach ($n in 1..(10 - $pins)) { "$panel .TabList .Tab:nth-child($n of .Tab) .fav::after { content: `"$(($pins + $n) % 10)`"; }" }
  }

  $managed = Get-Content "$here\sidebery\managed-storage.json" -Raw | ConvertFrom-Json -AsHashtable
  $managed.data.sidebarCSS = (Get-Content "$here\sidebery\sidebar.css" -Raw) + "`n/* generated by install.ps1 */`n" + ($badges -join "`n")
  $outDir = New-Item -ItemType Directory -Force "$env:LOCALAPPDATA\LibreWolfConfig"
  $outFile = Join-Path $outDir 'sidebery.json'
  $managed | ConvertTo-Json -Depth 10 | Set-Content $outFile -Encoding utf8NoBOM
  $key = "HKCU:\Software\Mozilla\ManagedStorage\$sideberyId"
  New-Item -Path $key -Force | Out-Null
  Set-ItemProperty -Path $key -Name '(default)' -Value $outFile
}
if ($Css) { Write-SideberyConfig; Write-Host 'Sidebery config rebuilt: press F1 twice in LibreWolf'; return }

if (Get-Process librewolf -ErrorAction SilentlyContinue) { throw 'LibreWolf is running, close it first.' }

# --- browser -------------------------------------------------------------------
if (-not $Quick -and ($Install -or -not (Test-Path $exe))) {
  $rel = Invoke-RestMethod 'https://codeberg.org/api/v1/repos/librewolf/bsys6/releases/latest'
  $asset = $rel.assets | Where-Object name -match 'windows-x86_64-portable\.zip$'
  $sum = $rel.assets | Where-Object name -eq "$($asset.name).sha256sum"
  $tmp = New-Item -ItemType Directory (Join-Path $env:TEMP "librewolf-$(Get-Random)")
  $zip = Join-Path $tmp $asset.name
  Write-Host "Downloading $($asset.name)"
  Invoke-WebRequest $asset.browser_download_url -OutFile $zip
  if ($sum) {
    $want = ((Invoke-RestMethod $sum.browser_download_url) -split '\s+')[0]
    if ((Get-FileHash $zip -Algorithm SHA256).Hash -ne $want) { throw "Checksum mismatch for $($asset.name)" }
  }
  Expand-Archive $zip -DestinationPath $tmp
  $src = Get-ChildItem $tmp -Directory | Select-Object -First 1
  New-Item -ItemType Directory -Force $appDir | Out-Null
  Copy-Item "$($src.FullName)\*" $appDir -Recurse -Force
  Remove-Item $tmp -Recurse -Force
}

$lnk = "$env:APPDATA\Microsoft\Windows\Start Menu\Programs\LibreWolf.lnk"
if (-not (Test-Path $lnk)) {
  $s = (New-Object -ComObject WScript.Shell).CreateShortcut($lnk)
  $s.TargetPath = $exe
  $s.WorkingDirectory = Split-Path $exe
  $s.Save()
}

# --- profile -------------------------------------------------------------------
function Get-DefaultProfile {
  foreach ($ini in "$dataDir\installs.ini", "$dataDir\profiles.ini") {
    if (-not (Test-Path $ini)) { continue }
    $hit = Select-String -Path $ini -Pattern '^Default=(Profiles/.+)$' | Select-Object -First 1
    if ($hit) { return Join-Path $dataDir $hit.Matches[0].Groups[1].Value }
  }
}
$profileDir = Get-DefaultProfile
if (-not $profileDir) {
  Write-Host 'Creating profile (first headless start)'
  $p = Start-Process $exe -ArgumentList '--headless', 'about:blank' -PassThru
  Start-Sleep 8
  Stop-Process -Id $p.Id -Force -ErrorAction SilentlyContinue
  Get-Process librewolf -ErrorAction SilentlyContinue | Stop-Process -Force
  $profileDir = Get-DefaultProfile
}
if (-not $profileDir) { throw 'No LibreWolf profile found' }
Write-Host "Profile: $profileDir"

# Privileged autoconfig: overrides.cfg runs with chrome privileges (needs the pref in the install dir,
# which LibreWolf updates replace, so it's rewritten on every run)
Set-Content "$appDir\LibreWolf\defaults\pref\autoconfig-privileged.js" 'pref("general.config.sandbox_enabled", false);' -Encoding utf8NoBOM
New-Item -ItemType Directory -Force "$env:USERPROFILE\.librewolf" | Out-Null
Copy-Item "$here\librewolf.overrides.cfg" "$env:USERPROFILE\.librewolf\librewolf.overrides.cfg" -Force

Copy-Item "$here\user.js" $profileDir -Force
New-Item -ItemType Directory -Force "$profileDir\chrome" | Out-Null
Copy-Item "$here\chrome\*" "$profileDir\chrome" -Force

# --- extensions ----------------------------------------------------------------
$extDir = New-Item -ItemType Directory -Force "$profileDir\extensions"
Add-Type -AssemblyName System.IO.Compression.FileSystem

# local unsigned add-ons -> xpi named after their gecko id
# (only replaced when the content changed: a new xpi makes LibreWolf reinstall it and drop its startup cache)
foreach ($dir in Get-ChildItem "$here\extensions" -Directory) {
  $id = (Get-Content "$($dir.FullName)\manifest.json" -Raw | ConvertFrom-Json).browser_specific_settings.gecko.id
  $xpi = Join-Path $extDir "$id.xpi"
  $tmpXpi = Join-Path $env:TEMP "$id.$(Get-Random).xpi"
  [IO.Compression.ZipFile]::CreateFromDirectory($dir.FullName, $tmpXpi)
  if ((Test-Path $xpi) -and (Get-FileHash $xpi).Hash -eq (Get-FileHash $tmpXpi).Hash) {
    Remove-Item $tmpXpi
  } else {
    Move-Item $tmpXpi $xpi -Force
    Write-Host "  built $id"
  }
}

# AMO add-ons (extensions.txt: "<amo-slug>  # comment")
foreach ($line in $(if ($Quick) { @() } else { Get-Content "$here\extensions.txt" })) {
  $slug = ($line -replace '#.*$', '').Trim()
  if (-not $slug) { continue }
  $info = Invoke-RestMethod "https://addons.mozilla.org/api/v5/addons/addon/$slug/"
  $xpi = Join-Path $extDir "$($info.guid).xpi"
  if ((Test-Path $xpi) -and -not $Update) { continue }
  Invoke-WebRequest $info.current_version.file.url -OutFile $xpi
  Write-Host "  fetched $slug $($info.current_version.version)"
}

# Pre-grant Sidebery's optional tabHide permission (needed to hide inactive workspaces' tabs)
$prefsFile = "$profileDir\extension-preferences.json"
$extPrefs = if (Test-Path $prefsFile) { Get-Content $prefsFile -Raw | ConvertFrom-Json -AsHashtable } else { @{} }
if (-not $extPrefs[$sideberyId]) { $extPrefs[$sideberyId] = @{ permissions = @(); origins = @() } }
$perms = [Collections.Generic.List[string]]@($extPrefs[$sideberyId].permissions)
if ('tabHide' -notin $perms) { $perms.Add('tabHide') }
$extPrefs[$sideberyId].permissions = $perms
$extPrefs | ConvertTo-Json -Depth 5 | Set-Content $prefsFile -Encoding utf8NoBOM

# Sidebery shortcuts (sidebery/shortcuts.json), stored where about:addons > Manage shortcuts keeps them.
# Sidebery has to have been installed once (first start) so its installDate is known.
$addons = (Get-Content "$profileDir\extensions.json" -Raw -ErrorAction SilentlyContinue | ConvertFrom-Json).addons
$sidebery = $addons | Where-Object id -eq $sideberyId
if ($sidebery) {
  $settingsFile = "$profileDir\extension-settings.json"
  $store = if (Test-Path $settingsFile) { Get-Content $settingsFile -Raw | ConvertFrom-Json -AsHashtable } else { @{ version = 3 } }
  if (-not $store.commands) { $store.commands = @{} }
  $shortcuts = Get-Content "$here\sidebery\shortcuts.json" -Raw | ConvertFrom-Json -AsHashtable
  foreach ($name in $shortcuts.Keys) {
    $entry = @{ id = $sideberyId; installDate = [long]$sidebery.installDate; value = @{ shortcut = $shortcuts[$name] }; enabled = $true }
    $store.commands[$name] = @{ precedenceList = @($entry) }
  }
  $store | ConvertTo-Json -Depth 10 | Set-Content $settingsFile -Encoding utf8NoBOM
} else {
  Write-Host '  Sidebery not installed yet: start LibreWolf once, then rerun for its shortcuts'
}

Write-SideberyConfig

Write-Host 'Done. Start LibreWolf from the Start menu.'
